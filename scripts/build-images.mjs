// Turns the full-resolution app screens in assets/screens/ into responsive AVIF + WebP files
// in public/screens/, and writes src/content/screens.generated.ts with each screen's intrinsic
// size and the widths available, so <Screen> can emit srcset/sizes and reserve layout space.
//
//   npm run images
import { readdir, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const src = path.join(root, "assets", "screens");
const out = path.join(root, "public", "screens");
const CANDIDATES = [400, 640, 960, 1280, 1680, 2160];

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const manifest = {};
for (const file of (await readdir(src)).filter((f) => f.endsWith(".png")).sort()) {
  const name = file.replace(/\.png$/, "");
  const input = sharp(path.join(src, file));
  const { width, height } = await input.metadata();
  const widths = CANDIDATES.filter((w) => w < width);
  if (width <= 2160) widths.push(width);
  for (const w of widths) {
    const resized = sharp(path.join(src, file)).resize({ width: w });
    await resized.clone().avif({ quality: 52, effort: 5 }).toFile(path.join(out, `${name}-${w}.avif`));
    await resized.clone().webp({ quality: 80, effort: 5 }).toFile(path.join(out, `${name}-${w}.webp`));
  }
  manifest[name] = { width, height, widths };
  console.log(`${name.padEnd(28)} ${width}x${height} → ${widths.join(", ")}`);
}

const ts = `// Generated by scripts/build-images.mjs. Do not edit by hand; run \`npm run images\`.
export const screens = ${JSON.stringify(manifest, null, 2)} as const;

export type ScreenName = keyof typeof screens;
`;
await writeFile(path.join(root, "src", "content", "screens.generated.ts"), ts);
